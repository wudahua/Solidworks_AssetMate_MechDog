"""Real stdio probe for the published tool contract. No SolidWorks required.

    python tests/stdio_contract.py

Why this exists
---------------
Ten consecutive review reports (v0.8.235 .. v0.8.290) found the same thing by hand:
`tools/list` published `additionalProperties: <absent>` on every top-level inputSchema.
Each round someone started a stdio client, counted the schemas, and wrote the number into
a report — and each round the fix was about something else. This turns that manual probe
into one command.

It deliberately drives a REAL subprocess over stdio rather than importing `server` in
process, because the two paths differ: `main()` installs `_install_argument_guard`, and
only the subprocess can prove that the published schema and the runtime guard coexist.

Not part of `check_all.py` on purpose: the offline gate is dependency-free, while this
needs the MCP SDK and spawns a process. Run it before a release.

Checks
------
  1. every tool's TOP-LEVEL inputSchema declares `additionalProperties: false`
  2. nested schemas generated by pydantic are NOT rewritten to false
  3. `list_tool_profiles` still validates and self-reports the seal
  4. an unknown argument is REFUSED by the runtime guard (not by the schema declaration)

Checks 1 and 4 are independent. With mcp 1.30.0, sealing the schema alone does NOT make
`ping({"bogus_param": 123})` fail — pydantic's `extra="ignore"` drops the key. Only
`_install_argument_guard` refuses it. See docs/com-quirks.md (2026-11-10, v0.8.292).
"""
from __future__ import annotations

import asyncio
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from mcp import ClientSession, StdioServerParameters  # noqa: E402
from mcp.client.stdio import stdio_client  # noqa: E402


def _text(result):
    """Pull the JSON string out of a CallToolResult, regardless of isError."""
    parts = []
    for block in result.content or ():
        text = getattr(block, "text", None)
        if text:
            parts.append(text)
    return "\n".join(parts)


async def _probe():
    env = dict(os.environ)
    env["PYTHONPATH"] = os.path.join(ROOT, "src") + os.pathsep + env.get("PYTHONPATH", "")
    params = StdioServerParameters(
        command=sys.executable,
        args=["-c", "from solidworks_assetmate_mechdog.server import main; main()"],
        env=env,
        cwd=ROOT,
    )

    results = []

    def record(name, ok, detail):
        results.append((name, ok, detail))
        print("%-46s %s  %s" % (name, "PASS" if ok else "FAIL", detail))

    async with stdio_client(params) as (read, write):
        async with ClientSession(read, write) as session:
            init = await session.initialize()
            version = getattr(init, "serverInfo", None)
            version = getattr(version, "version", "?")
            record("serverInfo.version", bool(version) and version != "?", str(version))

            tools = (await session.list_tools()).tools
            record("tools/list returns tools", bool(tools), "%d tools" % len(tools))

            missing = [t.name for t in tools
                       if (t.inputSchema or {}).get("additionalProperties") is not False]
            record("every top-level schema is sealed", not missing,
                   "%d/%d sealed%s" % (len(tools) - len(missing), len(tools),
                                       "" if not missing else " missing=%s" % missing[:5]))

            nested = [
                (t.name, key, prop.get("additionalProperties"))
                for t in tools
                for key, prop in (t.inputSchema.get("properties") or {}).items()
                if isinstance(prop, dict) and "additionalProperties" in prop
            ]
            record("nested schemas untouched",
                   all(value is True for _, _, value in nested),
                   "%d nested declarations, all true=%s"
                   % (len(nested), all(v is True for _, _, v in nested)))

            good = await session.call_tool("list_tool_profiles", {})
            try:
                payload = json.loads(_text(good))
            except Exception as exc:
                payload = {"parse_error": str(exc), "raw": _text(good)[:200]}
            seal = payload.get("input_schema_seal") or {}
            record("normal call validates + seal self-reports",
                   payload.get("ok") is True and seal.get("ok") is True
                   and seal.get("sealed") == len(tools),
                   "seal=%r isError=%s" % (seal, getattr(good, "isError", None)))

            bad = await session.call_tool("list_tool_profiles", {"bogus_param": 123})
            bad_text = _text(bad)
            try:
                bad_payload = json.loads(bad_text)
            except Exception:
                bad_payload = {}
            refused = (bool(getattr(bad, "isError", False))
                       and bad_payload.get("error") == "unknown_argument"
                       and "bogus_param" in (bad_payload.get("unknown") or []))
            record("unknown argument refused by runtime guard", refused,
                   "isError=%s error=%s" % (getattr(bad, "isError", None),
                                            bad_payload.get("error")))

    print("-" * 78)
    failed = [name for name, ok, _ in results if not ok]
    print("%d passed / %d run" % (len(results) - len(failed), len(results)))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(asyncio.run(_probe()))
